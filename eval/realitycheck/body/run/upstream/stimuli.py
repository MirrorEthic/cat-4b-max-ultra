# ---------- body geometry ----------
def geodesic():
    import networkx as nx
    G = nx.Graph(); K = [l["key"] for l in LOCS]
    def e(a, b, w=1.0): G.add_edge(a, b, weight=w)
    for s in "LR":
        ch = ["shoulder", "upperarm", "elbow", "forearm", "wrist"]
        for a, b in zip(ch, ch[1:]): e(a + s, b + s)
        e("wrist" + s, "palm" + s); e("wrist" + s, "backhand" + s); e("palm" + s, "backhand" + s, 0.5)
        f = ["thumb", "index", "middle", "ring", "little"]
        for x in f: e(x + s, "palm" + s); e(x + s, "backhand" + s)
        for a, b in zip(f, f[1:]): e(a + s, b + s, 0.5)
        lg = ["hip", "thigh", "knee", "shin", "ankle"]
        for a, b in zip(lg, lg[1:]): e(a + s, b + s)
        e("ankle" + s, "heel" + s); e("ankle" + s, "sole" + s); e("heel" + s, "sole" + s, 0.5); e("sole" + s, "toes" + s)
        e("shoulder" + s, "upback"); e("shoulder" + s, "chest"); e("shoulder" + s, "neckB"); e("shoulder" + s, "neckF")
        e("hip" + s, "lowback"); e("hip" + s, "belly")
        e("cheek" + s, "ear" + s); e("cheek" + s, "lips"); e("cheek" + s, "forehead"); e("ear" + s, "crown")
        e("ear" + s, "neckB"); e("cheek" + s, "neckF", 1.5)
    e("hipL", "hipR", 1.5); e("shoulderL", "shoulderR", 2.0)
    e("chest", "belly"); e("upback", "lowback"); e("chest", "upback"); e("belly", "lowback")
    e("neckF", "neckB"); e("neckF", "chest"); e("neckB", "upback"); e("lips", "tongue", 0.5); e("lips", "neckF", 1.5)
    e("forehead", "crown"); e("crown", "neckB", 1.5)
    D = dict(nx.all_pairs_dijkstra_path_length(G))
    return np.array([[D[a][b] for b in K] for a in K])

def model_rdms():
    n = len(LOCS); L = LOCS
    side = np.array([l["side"] for l in L]); depth = np.array([l["depth"] for l in L])
    R = {}
    R["body path distance"] = geodesic()
    R["left vs right"] = np.abs(side[:, None] - side[None, :]) / 2
    R["same limb"] = np.array([[float(a["limb"] != b["limb"]) for b in L] for a in L])
    R["distal-proximal"] = np.abs(depth[:, None] - depth[None, :]).astype(float)
    R["same part, either side"] = np.array([[float(a["type"] != b["type"]) for b in L] for a in L])
    w = [set(l["phrase"].replace("the ", "").split()) - {"of"} for l in L]
    R["shared words (lexical)"] = np.array([[1 - len(a & b) / len(a | b) for b in w] for a in w])
    return R

def build():
    rows = []
    for cond, pos in POSS.items():
        for i, l in enumerate(LOCS):
            loc = _inner(l["phrase"], pos) if l["phrase"].startswith("the ") else f"{pos} {l['phrase']}"
            for t, tpl in enumerate(TEMPLATES):
                rows.append(dict(cond=cond, loc=l["key"], li=i, tpl=t, text=tpl.format(L=loc)))
    for k, vs in MOVES.items():
        for t, v in enumerate(vs):
            rows.append(dict(cond="move", loc=k, li=-1, tpl=t, text=v))
    return rows

