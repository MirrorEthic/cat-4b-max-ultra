LOCS = []  # dicts
for side, sname in [(1, "left"), (-1, "right")]:
    s = "L" if side == 1 else "R"
    for k, p, d in ARM:
        # possessive form: "your left back of the hand" is clumsy -> special-case
        ph = f"{sname} {p}"
        LOCS.append(dict(key=k + s, phrase=ph, side=side, limb="arm" + s, depth=d, type=k))
    for k, p, d in LEG:
        ph = f"{sname} {p}"
        LOCS.append(dict(key=k + s, phrase=ph, side=side, limb="leg" + s, depth=d, type=k))
for k, p, sd, lb in HEAD + TORSO:
    LOCS.append(dict(key=k, phrase=p, side=sd, limb=lb, depth=0, type=k.rstrip("LR") if k.endswith(("L", "R")) and k[:-1] in ("cheek", "ear") else k))

# phrases starting with "the ..." take the possessive inside: "the back of your left hand"
def with_pos(phrase, pos):
    if phrase.startswith("the "):
        return phrase.replace("the ", f"{pos} ", 1).replace(f"of the ", "of the ", 1) if False else _inner(phrase, pos)
    return f"{pos} {phrase}"

def _inner(phrase, pos):
    # "the back of the left hand" -> "the back of your left hand"
    head, tail = phrase.rsplit(" of the ", 1)
    return f"{head} of {pos} {tail}"

